public class Aula28ForExercicio {
    public static void main(String[] args) {
        // Exercício resolvido: exibir números pares de 0 a 20.
        for (int numero = 0; numero <= 20; numero++) {
            if (numero % 2 == 0) {
                System.out.println(numero);
            }
        }
    }
}
