public class Aula10ConvencoesVariaveis {
    public static void main(String[] args) {
        // camelCase e nomes que expressem a finalidade da variável
        String nome = "João";
        int idade = 26;
        double salarioMensal = 2000.00;
        boolean estaEstudando = true;
        char inicialNome = 'J';

        System.out.println("Nome: " + nome);
        System.out.println("Idade: " + idade);
        System.out.println("Salário mensal: " + salarioMensal);
        System.out.println("Está estudando? " + estaEstudando);
        System.out.println("Inicial do nome: " + inicialNome);
    }
}
