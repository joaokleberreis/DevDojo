public class Aula16OperadoresRelacionais {
    public static void main(String[] args) {
        int idade = 20;
        int idadeMinima = 18;

        System.out.println("Igual: " + (idade == idadeMinima));
        System.out.println("Diferente: " + (idade != idadeMinima));
        System.out.println("Maior: " + (idade > idadeMinima));
        System.out.println("Maior ou igual: " + (idade >= idadeMinima));
        System.out.println("Menor: " + (idade < idadeMinima));
        System.out.println("Menor ou igual: " + (idade <= idadeMinima));
    }
}
